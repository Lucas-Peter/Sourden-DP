#!/usr/bin/env node
/**
 * SOURDEN — update-collection
 * ---------------------------------------------------------------------------
 * Maintains an EXISTING product collection: replace a product photo, or add a
 * new product (and photo) to a collection that is already on the site.
 *
 *   # 换图：把第 N 张产品图换成新图（可选同时改 alt）
 *   node scripts/update-collection.mjs <slug> <新图路径> --replace <序号|code> [--alt "新说明"]
 *
 *   # 增图：在集合末尾新增一个产品（含新图）
 *   node scripts/update-collection.mjs <slug> <新图路径> --add \
 *        --code "SJ-013" --name "..." --desc "..." --alt "..."
 *
 * ── WHAT IT DOES ───────────────────────────────────────────────────────────
 *   --replace  crops the new photo to the card's 4:5 frame (1000 × 1250,
 *              centre cover), encodes WebP ~78% and OVERWRITES the existing
 *              file in place (same name). This matches the pre-launch rule in
 *              IMAGES.md: while the site is not live, swap images in place and
 *              hard-refresh / purge to see the new one — the responsive `@NNNw`
 *              variants are regenerated by `gen-srcset.mjs` on the next build.
 *              With `--alt`, the slot's `alt` (media.js) and the product's
 *              `altText` (collection-<slug>.js) are updated too.
 *
 *   --add      crops the photo, writes it as the next numbered file (the file
 *              prefix + number are derived from the collection's existing
 *              slots, so `soccer-jersey-12.webp` becomes `soccer-jersey-13`),
 *              registers a new image slot in media.js and appends the product
 *              record to the collection data file.
 *
 * Both actions read the collection from its data file (`collection-<slug>.js`)
 * and locate the matching image slot in `media.js` by `imageKey` — nothing else
 * is touched. `--dry-run` crops the photo into `incoming/.preview/` and prints
 * the edits instead of writing them.
 * ---------------------------------------------------------------------------
 */
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const NN = (n) => String(n).padStart(2, '0');
const camelSlugOf = (slug) => slug.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function fail(msg) {
  console.error(`\n[update-collection] ${msg}\n`);
  process.exit(1);
}

/* -------------------------------------------------------------- arg parsing */

const BOOL_FLAGS = new Set(['add']);
const VAL_FLAGS = new Set(['replace', 'alt', 'code', 'name', 'desc']);

const args = process.argv.slice(2);
const opts = {};
const positional = [];
let DRY = false;

for (let i = 0; i < args.length; i++) {
  const a = args[i];
  if (a === '--dry-run') {
    DRY = true;
  } else if (a.startsWith('--')) {
    const key = a.slice(2);
    if (BOOL_FLAGS.has(key)) opts[key] = true;
    else if (VAL_FLAGS.has(key)) opts[key] = args[++i] ?? '';
    else fail(`未知参数 "${a}"`);
  } else {
    positional.push(a);
  }
}

const slug = positional[0];
const imagePath = positional[1];

if (!slug || !imagePath) {
  console.error(
    '用法:\n' +
      '  换图  node scripts/update-collection.mjs <slug> <新图> --replace <序号|code> [--alt "新说明"]\n' +
      '  增图  node scripts/update-collection.mjs <slug> <新图> --add --code ".." --name ".." --desc ".." --alt ".."\n'
  );
  process.exit(1);
}
if (!opts.replace && !opts.add) fail('需要 --replace 或 --add 之一');
if (opts.replace && opts.add) fail('--replace 与 --add 不能同时用');
if (!fs.existsSync(imagePath)) fail(`找不到图片: ${imagePath}`);

/* ------------------------------------------------------- load the collection */

const dataFile = path.join(ROOT, 'src', 'data', `collection-${slug}.js`);
if (!fs.existsSync(dataFile)) fail(`集合数据文件不存在: ${dataFile}（slug 可能拼错）`);

const camelSlug = camelSlugOf(slug);
const mod = await import(pathToFileURL(dataFile).href);
const collection = mod[camelSlug];
if (!collection) fail(`数据文件里找不到 export "${camelSlug}"`);

const products = collection.products;
const categoryName = collection.categoryName;

const mediaPath = path.join(ROOT, 'src', 'data', 'media.js');
let media = fs.readFileSync(mediaPath, 'utf8');

/* ------------------------------------------------------------ media helpers */

/**
 * Returns { start, end, text } of the `  <key>: { … },\n` slot in media.js.
 * Slot fields are single-line, so the first `\n  },` after the opening line is
 * the block's close.
 */
function findSlot(content, key) {
  const start = content.indexOf(`  ${key}: {`);
  if (start === -1) return null;
  const closeRel = content.indexOf('\n  },', start);
  if (closeRel === -1) return null;
  const end = closeRel + '\n  },'.length;
  return { start, end, text: content.slice(start, end) };
}

function slotField(slotText, field) {
  const m = slotText.match(new RegExp(`${field}: '([^']*)'`));
  return m ? m[1] : null;
}

/** Replace a single-quoted string field (e.g. `alt`) in a located block. */
function setFieldInBlock(block, field, value) {
  const f = block.text.indexOf(`${field}: '`);
  if (f === -1) fail(`槽里找不到字段 "${field}"`);
  const valStart = f + `${field}: '`.length;
  const valEnd = block.text.indexOf(`'`, valStart);
  if (valEnd === -1) fail(`字段 "${field}" 未闭合`);
  return block.text.slice(0, f) + `${field}: ${JSON.stringify(value)}` + block.text.slice(valEnd + 1);
}

/** Replace `altText: '…'` in collection-<slug>.js, located by `imageKey`. */
function setAltTextInData(content, imageKey, value) {
  const anchor = `imageKey: '${imageKey}'`;
  const a = content.indexOf(anchor);
  if (a === -1) fail(`数据文件里找不到 imageKey "${imageKey}"`);
  const f = content.indexOf(`altText: '`, a);
  if (f === -1) fail(`数据文件里找不到该产品的 altText`);
  const valStart = f + `altText: '`.length;
  const valEnd = content.indexOf(`'`, valStart);
  if (valEnd === -1) fail(`altText 未闭合`);
  return content.slice(0, f) + `altText: ${JSON.stringify(value)}` + content.slice(valEnd + 1);
}

/* --------------------------------------------------------------- crop photo */

const outName = (file) => path.join(DRY ? path.join(ROOT, 'incoming', '.preview') : path.join(ROOT, 'public', 'images'), file);

async function cropTo(file) {
  fs.mkdirSync(path.dirname(outName(file)), { recursive: true });
  let meta;
  try {
    meta = await sharp(imagePath).metadata();
  } catch (e) {
    fail(`图片打不开: ${e.message}`);
  }
  if ((meta.width || 0) < 1000 || (meta.height || 0) < 1250) {
    console.warn(`  ⚠ 源图 ${meta.width}×${meta.height}，小于 1000×1250，放大后可能偏糊。`);
  }
  await sharp(imagePath)
    .resize(1000, 1250, { fit: 'cover', position: 'centre' })
    .webp({ quality: 78 })
    .toFile(outName(file));
  console.log(`  ✓ 图 ${path.basename(imagePath)} → ${file}`);
}

/* ================================================================ --replace */

if (opts.replace) {
  const target = opts.replace.trim();
  const targetProduct = /^\d+$/.test(target)
    ? products.find((p) => p.sortOrder === parseInt(target, 10))
    : products.find((p) => p.code === target);

  if (!targetProduct) {
    fail(
      `找不到产品 "${target}"。可用: ` +
        products.map((p) => `${p.sortOrder}(${p.code})`).join(', ')
    );
  }

  const imageKey = targetProduct.imageKey;
  const slot = findSlot(media, imageKey);
  if (!slot) fail(`media.js 里找不到槽 "${imageKey}"`);
  const file = slotField(slot.text, 'file');
  if (!file) fail(`槽 "${imageKey}" 缺 file 字段`);

  console.log(`[update-collection] 换图：${categoryName} #${targetProduct.sortOrder} (${targetProduct.code})\n`);
  console.log(`  目标槽  ${imageKey} → ${file}`);
  console.log(`  新图    ${path.basename(imagePath)}`);

  if (DRY) {
    await cropTo(file);
    if (opts.alt) {
      console.log(`  alt     更新为: ${opts.alt}（media.js 槽 + 数据文件 altText）`);
    }
    console.log('\n[dry-run] 未写入正式文件。确认后去掉 --dry-run 重跑。\n');
  } else {
    await cropTo(file);
    console.log(`  ✓ 已同名覆盖 public/images/${file}`);

    if (opts.alt) {
      const newSlotText = setFieldInBlock(slot, 'alt', opts.alt);
      media = media.slice(0, slot.start) + newSlotText + media.slice(slot.end);
      fs.writeFileSync(mediaPath, media);
      console.log(`  ✓ media.js 槽 ${imageKey} 的 alt 已更新`);

      let data = fs.readFileSync(dataFile, 'utf8');
      data = setAltTextInData(data, imageKey, opts.alt);
      fs.writeFileSync(dataFile, data);
      console.log(`  ✓ ${path.basename(dataFile)} 的 altText 已更新`);
    }

    console.log('\n[update-collection] 换图完成。\n');
    console.log('【下一步】本地验证：CODEBUDDY_SAFE_DELETE_ENABLED=0 npm run verify\n');
    console.log('【要上传 GitHub】');
    console.log('    public/images/' + file + '   ← 同名覆盖旧图');
    if (opts.alt) {
      console.log('    src/data/media.js           ← alt 变了');
      console.log('    src/data/' + path.basename(dataFile) + '   ← altText 变了');
    }
    console.log('   （带 @ 的响应式变体不要传，Cloudflare 构建时自动重生成）\n');
  }
}

/* ==================================================================== --add */

if (opts.add) {
  for (const k of ['code', 'name', 'desc', 'alt']) {
    if (!opts[k]) fail(`--add 需要 --${k}`);
  }

  const lastProduct = products[products.length - 1];
  const lastSlot = findSlot(media, lastProduct.imageKey);
  if (!lastSlot) fail(`media.js 里找不到最后一个槽 "${lastProduct.imageKey}"`);

  const lastFile = slotField(lastSlot.text, 'file');
  const lastLabel = slotField(lastSlot.text, 'label');
  const lastArtDirection = slotField(lastSlot.text, 'artDirection');

  const nextSort = products.length + 1;
  const nextNN = NN(nextSort);
  const imageKey = `${camelSlug}${nextNN}`;
  const newFile = lastFile.replace(/(\d+)\.webp$/, (_, n) => `${NN(parseInt(n, 10) + 1)}.webp`);
  const newLabel = (lastLabel || `${categoryName.toUpperCase()} ${nextNN}`).replace(/\d+$/, nextNN);
  const artDirection =
    lastArtDirection ||
    `One product photo from the ${categoryName} category, subject complete and centred. Provided by the owner (self-uploaded). Not AI-generated.`;

  console.log(`[update-collection] 增图：${categoryName} 新增第 ${nextSort} 个产品\n`);
  console.log(`  新槽  ${imageKey} → ${newFile}`);
  console.log(`  编号  ${opts.code} | ${opts.name}`);

  const newProduct = {
    id: `${slug}-${nextNN}`,
    code: opts.code,
    name: opts.name,
    imageKey,
    shortDescription: opts.desc,
    altText: opts.alt,
    sortOrder: nextSort,
  };

  const newSlotText =
    `  ${imageKey}: {\n` +
    `    file: ${JSON.stringify(newFile)}, width: 1000, height: 1250, ratio: '4:5',\n` +
    `    label: ${JSON.stringify(newLabel)},\n` +
    `    alt: ${JSON.stringify(opts.alt)},\n` +
    `    role: /** @type {ImageRole} */ ('product'),\n` +
    `    placeholder: false,\n` +
    `    artDirection: ${JSON.stringify(artDirection)},\n` +
    `  },`;

  const productBlock =
    `    {\n` +
    `      id: ${JSON.stringify(newProduct.id)},\n` +
    `      code: ${JSON.stringify(newProduct.code)},\n` +
    `      name: ${JSON.stringify(newProduct.name)},\n` +
    `      imageKey: ${JSON.stringify(newProduct.imageKey)},\n` +
    `      shortDescription: ${JSON.stringify(newProduct.shortDescription)},\n` +
    `      altText: ${JSON.stringify(newProduct.altText)},\n` +
    `      sortOrder: ${newProduct.sortOrder},\n` +
    `    },`;

  if (DRY) {
    await cropTo(newFile);
    console.log('\n── dry-run：以下插入未写入，供核对 ──\n');
    console.log('【media.js】在 ' + lastProduct.imageKey + ' 槽后插入:\n' + newSlotText + '\n');
    console.log('【' + path.basename(dataFile) + '】products 数组末尾追加:\n' + productBlock + '\n');
    console.log('[dry-run] 完成，未写入正式文件。确认后去掉 --dry-run 重跑。\n');
  } else {
    await cropTo(newFile);
    console.log(`  ✓ 新图 → public/images/${newFile}`);

    const insertion = lastSlot.end;
    media = media.slice(0, insertion) + `\n${newSlotText}` + media.slice(insertion);
    fs.writeFileSync(mediaPath, media);
    console.log(`  ✓ media.js 已新增槽 "${imageKey}"`);

    let data = fs.readFileSync(dataFile, 'utf8');
    const lastProductIdx = data.indexOf(`imageKey: '${lastProduct.imageKey}'`);
    if (lastProductIdx === -1) fail(`数据文件里找不到最后一个产品 "${lastProduct.imageKey}"`);
    // find the close of that product block: the `    },` after its imageKey
    const closeRel = data.indexOf('\n    },', lastProductIdx);
    if (closeRel === -1) fail(`最后一个产品块未闭合`);
    const closeEnd = closeRel + '\n    },'.length;
    data = data.slice(0, closeEnd) + `\n${productBlock}` + data.slice(closeEnd);
    fs.writeFileSync(dataFile, data);
    console.log(`  ✓ ${path.basename(dataFile)} 已追加产品 "${opts.code}"`);

    console.log('\n[update-collection] 增图完成。\n');
    console.log('【下一步】本地验证：CODEBUDDY_SAFE_DELETE_ENABLED=0 npm run verify\n');
    console.log('【要上传 GitHub】');
    console.log('  新增（每个都要传）:');
    console.log('    public/images/' + newFile);
    console.log('  修改（传新版覆盖）:');
    console.log('    src/data/media.js');
    console.log('    src/data/' + path.basename(dataFile));
    console.log('\n  不要上传：public/images/' + slug + '-*@*.webp（响应式变体，构建时自动生成）、incoming/、dist/\n');
  }
}
